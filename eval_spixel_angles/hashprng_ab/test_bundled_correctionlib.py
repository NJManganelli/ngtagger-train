import sys
import correctionlib
print("bundled correctionlib:", correctionlib.__version__)
cset = correctionlib.CorrectionSet.from_file("/work/spxsmoke/spx_angle_response_Conv1D_Full-2bit_v4fixed.json")
names = sorted(cset)
print("corrections:", len(names))
comp = sorted(cset.compound)
print("compounds:", comp)
pr = (2, 0.123456789, -0.4, -3.81)
z = cset["spx_angle_prng"].evaluate(*pr)
zb = cset["spx_angle_prng_beta"].evaluate(*pr)
u = cset["spx_angle_valid_flat"].evaluate(*pr)
sm = cset.compound["spx_angle_alpha_smear"].evaluate(*pr)
sig = cset["spx_angle_alpha_sigma"].evaluate(*pr)
b = cset["spx_angle_alpha_bias"].evaluate(*pr)
fused = cset.compound["spx_angle_alpha_shift"].evaluate(*pr, 1.0)
fused_b = cset.compound["spx_angle_beta_shift"].evaluate(*pr, 1.0)
print(f"z={z!r} zb={zb!r} u={u!r}")
print(f"smear={sm!r} sigma*z={sig*z!r} match={abs(sm-sig*z)<1e-15}")
print(f"fused={fused!r} bias+smear={b+sm!r} diff={fused-(b+sm)!r}")
print(f"fused_beta={fused_b!r}")
print("repeat-determinism:", fused == cset.compound["spx_angle_alpha_shift"].evaluate(*pr, 1.0))
sys.exit(0)
